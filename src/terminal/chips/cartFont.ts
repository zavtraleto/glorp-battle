/** Width of `text` in pixels (no trailing spacing). */
export function measureBig(text: string): number {
  return text.length === 0 ? 0 : text.length * BIG_ADVANCE - 1;
}

/** True when every character of `text` has a glyph (a test checks the data). */
export function hasBigGlyphs(text: string): boolean {
  return [...text].every((ch) => GLYPHS[ch] !== undefined);
}

/**
 * Draws `text` at `x, y` in one flat colour (decision 2026-09-20: no outline —
 * the panel behind is dark enough to carry light glyphs on its own, and an
 * outline at this size only eats into the strokes).
 */
export function drawBig(sink: PixelSink, text: string, x: number, y: number, color: string): void {
  sink.fillStyle = color;
  [...text].forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) return;
    const left = x + i * BIG_ADVANCE;
    glyph.forEach((row, ry) => {
      let run = 0;
      for (let rx = 0; rx <= BIG_W; rx++) {
        if (row[rx] === '#') {
          run++;
          continue;
        }
        // Fill whole runs: one rect per run instead of one per pixel.
        if (run > 0) sink.fillRect(left + rx - run, y + ry, run, 1);
        run = 0;
      }
    });
  });
}
